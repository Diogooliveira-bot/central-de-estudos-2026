// Reuses the published navigation catalog; stores only IDs and titles, no pedagogical text.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { gunzipSync } from 'node:zlib';
const root=path.resolve(import.meta.dirname,'..');
const content=fs.readFileSync(path.join(root,'central-module-catalog.js'),'utf8');
const catalog=JSON.parse(content.split('window.CentralModuleCatalog=')[1].trim().replace(/;$/,''));
const pad=(number)=>String(number).padStart(2,'0');
// Remove complete and incomplete markup without leaving open HTML tags in catalog metadata.
function stripTags(value) {
  const input=String(value??'');
  let out='', inside=false;
  for(const ch of input) {
    if(ch==='<'){ inside=true; continue; }
    if(ch==='>' && inside){ inside=false; continue; }
    if(!inside && ch!=='>')out+=ch;
  }
  return out;
}
const modules=Object.fromEntries(Object.entries(catalog).map(([subject,items])=>[subject,items.map(({number,title})=>({id:`${subject}-${pad(number)}`,title,chapters:[]}))]));
const w={};
const run=(file)=>vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),{window:w},{filename:file});
const titles=(subject,number,items)=>{
  const module=modules[subject]?.[number-1];
  if(!module)throw Error(`Missing module ${subject}-${number}`);
  module.chapters=items.filter(Boolean).map((title,index)=>({id:`${module.id}-c${pad(index+1)}`,title:String(title).replace(/\s+/g,' ').trim().slice(0,220)}));
};
// Metadata is extracted from the existing reader sections, without copying their text.
const portuguese=JSON.parse(gunzipSync(Buffer.from(fs.readFileSync(path.join(root,'portugues-autodidata-data.txt'),'utf8').trim(),'base64')));
for(const [id,html] of Object.entries(portuguese)){
  if(!/^m\d\d$/.test(id))continue;
  titles('pt',Number(id.slice(1)),[...String(html).matchAll(/<h2 class="pt-doc-h1"[^>]*>([\s\S]*?)<\/h2>/gi)].map((m)=>stripTags(m[1]).trim()));
}
for(const file of fs.readdirSync(path.join(root,'content/rlm-tjce-2026')).filter((name)=>/^aulas-.*\.js$/.test(name)))run(`content/rlm-tjce-2026/${file}`);
for(const [id,data] of Object.entries(w.RLM_CURSO_AULAS||{}))titles('rlm',Number(id.slice(1)),(data.theory||[]).map((part)=>part.title));
for(let n=1;n<=13;n++)run(`content/informatica/m${pad(n)}.js`);
for(const [id,data] of Object.entries(w.BC_INFO_CONTENT||{}))titles('info',Number(id.slice(1)),(data.full||[]).map((part)=>part.title));
for(const kind of ['cf','penal'])for(const file of fs.readdirSync(path.join(root,'content',kind)).filter((name)=>/^m\d\d-teoria-guiada-data\.js$/.test(name)))run(`content/${kind}/${file}`);
for(const [n,data] of Object.entries(w.BC_CF_GUIDED_MODULES||{}))titles('cf',Number(n),(data.topics||[]).map((part)=>part[0]));
for(const [n,data] of Object.entries(w.BC_PEN_GUIDED_MODULES||{}))titles('penal',Number(n),(data.topics||[]).map((part)=>part[0]));
for(const file of fs.readdirSync(path.join(root,'content/civil')).filter((name)=>/^m\d\d-teoria-guiada-data\.js$/.test(name)))run(`content/civil/${file}`);
for(const [n,data] of Object.entries(w.BC_CIV_GUIDED_MODULES||{}))titles('civil',Number(n),(data.topics||[]).map((part)=>part[0]));
for(const file of fs.readdirSync(path.join(root,'content/cpc')).filter((name)=>/^cpc-review-didactic-.*\.js$/.test(name)))run(`content/cpc/${file}`);
for(const [n,data] of Object.entries(w.CPC_DIDACTIC_REVIEW||{}))titles('cpc',Number(n),(data.sections||[]).map((part)=>part[0]));
run('content/cpp/cpp-native-content-packed.js');
const cpp=JSON.parse(gunzipSync(Buffer.from(w.CPP_NATIVE_PACKED_B64,'base64')));
for(const data of Object.values(cpp))titles('cpp',Number(data.number),[...String(data.completeHtml||'').matchAll(/<h4\b[^>]*>([\s\S]*?)<\/h4>/gi)].map((m)=>stripTags(m[1]).trim()));
run('content/adm/adm-session-index.js');
for(const [n,sections] of Object.entries(w.ADM_SESSION_INDEX||{}))titles('adm',Number(n),sections);
const output=`/* Generated by scripts/build-shared-module-catalog.mjs. Existing section titles and IDs only; no theory. */\nexport const SHARED_MODULES=${JSON.stringify(modules)};\n`;
const target=path.join(root,'lib/shared-module-catalog.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('Regenerate shared module catalog');}
else fs.writeFileSync(target,output);
