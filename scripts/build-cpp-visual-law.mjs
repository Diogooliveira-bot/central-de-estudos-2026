import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url),read=p=>JSON.parse(readFileSync(new URL(p,root),'utf8'));
const sources=read('audits/cpp-official-source-lines.json'),audit=read('audits/cpp-law-coverage.json');
const names={cpp:'CPP',cf:'Constituição Federal',cp:'Código Penal',cc:'Código Civil',cpc:'CPC/2015',cpc1973:'CPC/1973 — histórico, revogado',eca:'ECA',cpm:'Código Penal Militar',cppm:'Código de Processo Penal Militar',cadh:'CADH',lep:'LEP',ctb:'CTB',lc80:'LC 80/1994'};
const clean=t=>t.replace(/【\d+†([^†】]+)(?:†[^】]*)?】/g,'$1').replace(/^#+\s*/,'').trim();
const all={},missing=[];
for(const [law,source]of Object.entries(sources)){
 const lines=Object.entries(source.lines).map(([n,t])=>[+n,clean(t)]).sort((a,b)=>a[0]-b[0]);
 const starts=lines.flatMap(([n,t])=>{const m=/^Art(?:igo)?\.?\s*(\d+(?:\.\d{3})?)[º°]?(?:\s*[-–]\s*([A-Z]))?(?:\.|\s|$)/i.exec(t);return m?[[n,m[1].replace('.','')+(m[2]?'-'+m[2].toUpperCase():'')]]:[]});
 all[law]={};
 for(let i=0;i<starts.length-1;i++){
  const [from,id]=starts[i],to=starts[i+1][0];if(all[law][id])continue;
  if(law==='cf'&&from>4550)continue; // ADCT has its own numbering.
  const gaps=[];for(let n=from;n<to;n++)if(!(n in source.lines))gaps.push(n);
  if(gaps.length){all[law][id]={incomplete:true,from,to,gaps};continue;}
  let paragraphs=lines.filter(([n])=>n>=from&&n<to).map(([,t])=>t).filter(Boolean);
  const heading=paragraphs.findIndex((t,j)=>j>0&&/^(?:CAPÍTULO|TÍTULO|LIVRO|Seção|Subseção)\b/i.test(t));if(heading>=0)paragraphs=paragraphs.slice(0,heading);
  // Remove the next article's editorial heading, never a legal provision or note.
  while(paragraphs.length>1&&!/[.;:!?\)\]”]$/.test(paragraphs.at(-1))&&!/^(?:§|Parágrafo|[IVXLCDM]+\s*[-–]|[a-z]\))/.test(paragraphs.at(-1)))paragraphs.pop();
  all[law][id]={label:(names[law]||'Lei '+law.slice(1))+' — art. '+id,law,ref:id,paragraphs,officialUrl:source.url,sourceLines:[from,to-1]};
 }
}
// The official compilation groups these repealed provisions on one line.
for(const [n,t]of Object.entries(sources.cpp.lines))if(/^Arts\. 498 a 502\./.test(t))for(let id=498;id<=502;id++)all.cpp[id]={label:'CPP — art. '+id+' (revogado)',law:'cpp',ref:String(id),paragraphs:[clean(t)],officialUrl:sources.cpp.url,sourceLines:[+n,+n]};
const modules={};
for(const [n,module]of Object.entries(audit.modules)){
 modules[n]=[];
 for(const r of module.references){const item=all[r.law]?.[r.ref];if(!item||item.incomplete){missing.push({module:+n,...r,source:item});continue;}modules[n].push({...item,anchor:r.context,section:r.section});}
}
writeFileSync(new URL('audits/cpp-law-missing.json',root),JSON.stringify(missing,null,2)+'\n');
console.log('Missing:',missing.length,missing.map(x=>x.module+':'+x.law+':'+x.ref+(x.source?' (gap '+x.source.from+'-'+x.source.to+')':'')).join(' '));
if(process.argv.includes('--write')){
 if(missing.length)throw new Error('Resolve every reference before generating');
 // Share article text across modules to avoid duplicating the legal corpus in the download.
 const articles={};for(const items of Object.values(modules))for(const x of items){const {anchor,section,...article}=x;articles[x.law+':'+x.ref]=article;}
 const data={verifiedAt:'2026-11-05',articles,modules:Object.fromEntries(Object.entries(modules).map(([n,items])=>[n,items.map(x=>({key:x.law+':'+x.ref,anchor:x.anchor,section:x.section}))]))};
 writeFileSync(new URL('content/cpp/cpp-visual-law.js',root),'/* Literal statutory text from official sources. Generated by scripts/build-cpp-visual-law.mjs. */\nwindow.CPP_VISUAL_LAW='+JSON.stringify(data)+';\n');
 console.log(Object.keys(articles).length+' articles; '+Object.values(modules).reduce((n,a)=>n+a.length,0)+' module references');
}
