// Compact identifiers for reading saved progress before course material is downloaded.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const context=vm.createContext({console,setTimeout(){},addEventListener(){},document:{readyState:'complete'},localStorage:{getItem(){return null},setItem(){}}});
vm.runInContext('window=globalThis',context);
const run=(p,code=read(p))=>vm.runInContext(code,context,{filename:p});
for(const kind of ['cf','cpc']){
 for(const p of fs.readdirSync(path.join(root,'central-structural-v66119')).filter(p=>p.startsWith(kind+'-questions-')).sort())run('central-structural-v66119/'+p);
}
const runtime=read('central-structural-v66119/runtime.js');
const start=runtime.indexOf('const CPC_WEEKS=');
run('weeks',runtime.slice(start,runtime.indexOf(';\n',start)+1)+'\nwindow.__CPC_WEEKS=CPC_WEEKS;window.__cpcPool=w=>CPC_QUESTIONS.filter(q=>w.topics.includes(q.t));');
const capture=(p,stop,expression)=>run(p,read(p).split(stop)[0]+`\nwindow.__selected=${expression};\n})(window);`);
capture('cpc-study-system-v1.js','function nativeChapterCount',"{summary:internalQuestions('w1','summary').map(q=>q.id),full:internalQuestions('w1','full').map(q=>q.id)}");
const quiz={1:JSON.parse(JSON.stringify(context.__selected))};
for(let n=2;n<=6;n++){
 const selector=n===6?'questions':'qs';
 capture(`cpc-study-m0${n}.js`,'function native(',`{summary:${selector}('summary').map(q=>q.id),full:${selector}('full').map(q=>q.id)}`);
 quiz[n]=JSON.parse(JSON.stringify(context.__selected));
}
for(const kind of ['cpc','penal'])for(const p of fs.readdirSync(path.join(root,'content',kind)).filter(p=>/native-data.*\.js$/.test(p)).sort()){
 let code=read(`content/${kind}/${p}`);
 if(kind==='cpc'&&p.startsWith('m08'))code=code.split('})(window);')[0]+'})(window);';
 run(`content/${kind}/${p}`,code);
}
run('content/adm/adm-native-index.js');
run('content/cpp/cpp-native-index.js');
const data={cpc:{},penal:{},admModuleIds:Object.keys(context.ADM_NATIVE_INDEX.modules),cppModules:context.CPP_NATIVE_INDEX.modules.map(({uid,number,title})=>({uid,number,title})),cfQuestionIds:vm.runInContext('CF_QUESTIONS.map(q=>q.id)',context)};
for(const kind of ['cpc','penal'])for(const [id,m] of Object.entries(context.BASE_NATIVE_CONTENT[kind])){
 data[kind][id]={chapters:{},questions:{}};
 for(const mode of ['summary','complete']){
  data[kind][id].chapters[mode]=(m.chapters?.[mode]||[]).map(ch=>ch.id);
  data[kind][id].questions[mode]=(m.internalQuestions?.[mode]||[]).map(q=>q.id);
 }
 if(kind==='cpc'&&quiz[m.number])data[kind][id].quiz=quiz[m.number];
}
fs.writeFileSync(path.join(root,'central-home-progress-data.js'),'/* Generated by scripts/build-home-progress.mjs. */\nwindow.CentralHomeProgressData='+JSON.stringify(data)+';\n');
console.log('Progress identifiers generated');
