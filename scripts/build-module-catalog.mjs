// Public navigation metadata only. Never include theory, answers, links or user data.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ctx=vm.createContext({window:{},console});
const run=p=>vm.runInContext(read(p),ctx,{filename:p});
for(const kind of ['cf','cpc'])for(const f of fs.readdirSync(path.join(root,'content',kind)).filter(f=>/^m\d+-native-data\.js$/.test(f)).sort()){
 let src=read(`content/${kind}/${f}`);
 // CPC M08 appends a runtime installer after its pure data declaration.
 if(kind==='cpc'&&f.startsWith('m08'))src=src.split('})(window);')[0]+'})(window);';
 vm.runInContext(src,ctx,{filename:f});
}
for(const kind of ['adm','civil','cpp'])run(`content/${kind}/${kind}-native-index.js`);
// Metadados dos cursos já carregados pela Central; a teoria continua nos arquivos originais.
vm.runInContext(read('portugues-site.js'),vm.createContext({window:ctx.window,document:{getElementById:()=>null}}),{filename:'portugues-site.js'});
run('content/rlm-tjce-2026/estrutura.js');
for(const f of fs.readdirSync(path.join(root,'content/informatica')).filter(f=>/^m\d+\.js$/.test(f)).sort())run(`content/informatica/${f}`);
const w=ctx.window;
const projection=m=>({number:m.number, title:m.title});
const catalog={
 cf:Object.values(w.BASE_NATIVE_CONTENT.cf).map(projection),
 cpc:Object.values(w.BASE_NATIVE_CONTENT.cpc).map(projection),
 adm:Object.values(w.ADM_NATIVE_INDEX.modules).map(projection),
 civil:w.CIVIL_NATIVE_INDEX.modules.map(projection),
 cpp:w.CPP_NATIVE_INDEX.modules.map(projection),
 pt:w.CentralPortugueseCourse.modules.map(m=>({number:m.num,title:m.title})),
 rlm:w.RLM_TJCE_STRUCTURE.modulos.map(m=>({number:Number(m.id.slice(1)),title:m.titulo})),
 info:Object.values(w.BC_INFO_CONTENT).map(m=>({number:Number(m.id.slice(1)),title:m.title})),
};
// Use the current published remap, not the legacy Penal order.
const penal=read('ui/penal-m01-m17-runtime-remap.js').match(/const meta=(\{[\s\S]*?\n  \});/);
if(!penal)throw Error('Penal metadata missing');
catalog.penal=Object.values(vm.runInNewContext('('+penal[1]+')')).map(m=>({number:m.num,title:m.title}));
for(const [id,modules] of Object.entries(catalog)){
 modules.sort((a,b)=>a.number-b.number);
 if(!modules.length||modules.some((m,i)=>m.number!==i+1||!m.title))throw Error('Invalid catalog '+id);
}
const output='/* Generated by scripts/build-module-catalog.mjs; public titles only. */\nwindow.CentralModuleCatalog='+JSON.stringify(catalog)+';\n';
const target=path.join(root,'central-module-catalog.js');
if(process.argv.includes('--check')){if(read('central-module-catalog.js')!==output)throw Error('Regenerate module catalog');}
else fs.writeFileSync(target,output);
