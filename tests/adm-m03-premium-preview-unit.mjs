test('M03 aprovado: estrutura real e texto original preservados',()=>{
 const dom=new JSDOM('<article class="bc-native-article">'+html+'</article>');
 const article=dom.window.document.querySelector('article');
 assert.equal(article.querySelector('h1').textContent.trim(),'Atos Administrativos');
 assert.equal(article.querySelector('h1+p').textContent,'DIREITO ADMINISTRATIVOMÓDULO 03');
 const table=article.querySelector('.adm-table-scroll > .adm-reading-table');
 assert.ok(table,'tabela real não localizada');
 assert.equal(table.tHead.rows[0].cells.length,4);
 assert.equal(table.tBodies[0].rows.length,4);
 assert.equal(article.querySelectorAll('.adm-m3-book,.adm-m3-table-wrap').length,0);
 assert.match(html,/SESSÃO 01/);
 dom.window.close();
});
